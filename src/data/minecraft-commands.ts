// Minecraft command catalog for the BRUH Minecraft command generator.
// Covers vanilla Java Edition (1.20+) plus every plugin auto-installable from
// the BRUH Minecraft Server add-on. Commands are written to be valid for
// Paper / Purpur / Folia (the supported plugin platforms).

export type ArgType =
  | 'text'
  | 'longtext'
  | 'player'
  | 'target'
  | 'number'
  | 'select'
  | 'block'
  | 'item'
  | 'entity'
  | 'effect'
  | 'enchantment'
  | 'gamerule'
  | 'duration'
  | 'coords'
  | 'json';

export interface CommandArg {
  key: string;
  label: string;
  type: ArgType;
  required?: boolean;
  options?: string[];
  default?: string;
  placeholder?: string;
  hint?: string;
  min?: number;
  max?: number;
  step?: number;
}

export interface Command {
  id: string;
  category: string;
  name: string;            // includes leading slash
  description: string;
  permission?: string;     // permission node, often used with LuckPerms
  template: string;        // e.g. "/give {player} {item} {count}"
  args: CommandArg[];
  notes?: string;
  example?: string;
  wiki?: string;           // upstream docs URL
  tags?: string[];
}

export interface Category {
  id: string;
  name: string;
  tagline: string;
  iconPath: string;        // SVG <path d="..."> for the icon
  permissionsHint?: string; // wildcard node that grants the whole plugin
  wiki?: string;
}

